#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# One-command setup for Ubuntu / Debian / other Linux distributions.
#
#   ./scripts/setup-linux.sh
#
# The script installs the system requirements, creates a virtual
# environment, installs the pinned Python dependencies, builds the sandbox
# image and prepares the database.
# ---------------------------------------------------------------------------
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

BLUE="\033[1;34m"
GREEN="\033[1;32m"
YELLOW="\033[1;33m"
RED="\033[1;31m"
RESET="\033[0m"

info()  { echo -e "${BLUE}==>${RESET} $*"; }
ok()    { echo -e "${GREEN}✓${RESET} $*"; }
warn()  { echo -e "${YELLOW}!${RESET} $*"; }
fail()  { echo -e "${RED}✗${RESET} $*" >&2; exit 1; }

info "Secure AI Tool Execution & Permission Sandbox - Linux setup"

# ---------------------------------------------------------------- python
PYTHON_BIN="${PYTHON_BIN:-python3}"
command -v "$PYTHON_BIN" >/dev/null 2>&1 || fail "python3 is not installed."
PYTHON_VERSION="$("$PYTHON_BIN" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
if [[ "${PYTHON_VERSION}" < "3.12" ]]; then
    fail "Python 3.12 or newer is required (found ${PYTHON_VERSION})."
fi
ok "Python ${PYTHON_VERSION}"

# ----------------------------------------------------------------- docker
if ! command -v docker >/dev/null 2>&1; then
    warn "Docker is not installed. The sandbox backend requires Docker Engine."
    warn "Install it with: sudo apt-get install -y docker.io docker-compose-v2"
    warn "Then add your user to the 'docker' group: sudo usermod -aG docker \$USER"
else
    if docker info >/dev/null 2>&1; then
        ok "Docker daemon is reachable"
    else
        warn "The Docker daemon is not reachable. Start it with: sudo systemctl start docker"
    fi
fi

# ------------------------------------------------------------- virtualenv
if [[ ! -d .venv ]]; then
    info "Creating the virtual environment"
    "$PYTHON_BIN" -m venv .venv 2>/dev/null || {
        warn "python3-venv is missing; installing the system package"
        sudo apt-get update && sudo apt-get install -y python3-venv
        "$PYTHON_BIN" -m venv .venv
    }
fi
# shellcheck disable=SC1091
source .venv/bin/activate
ok "Virtual environment ready: $(python -c 'import sys; print(sys.prefix)')"

# ----------------------------------------------------------- dependencies
info "Installing the pinned Python dependencies"
pip install --upgrade pip setuptools wheel >/dev/null
pip install -r backend/requirements-dev.txt
ok "Python dependencies installed"

# ------------------------------------------------------------- frontend
if command -v npm >/dev/null 2>&1; then
    info "Installing the frontend dependencies"
    (cd frontend && npm install --no-audit --no-fund)
    ok "Frontend dependencies installed"
else
    warn "npm is not installed; the dashboard cannot be built."
fi

# ------------------------------------------------------------ environment
if [[ ! -f .env ]]; then
    cp .env.example .env
    SECRET="$(python -c 'import secrets; print(secrets.token_urlsafe(48))')"
    FERNET="$(python -c 'from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())')"
    {
        echo ""
        echo "# Generated by scripts/setup-linux.sh"
        echo "SAXIS_SECRET_KEY=${SECRET}"
        echo "SAXIS_PROVIDER_SECRET_KEY=${FERNET}"
    } >> .env
    ok "Created .env with generated secrets (review it before deploying)"
else
    ok ".env already exists"
fi

# --------------------------------------------------- docker socket group
if [ -S /var/run/docker.sock ]; then
    DOCKER_GID="$(stat -c '%g' /var/run/docker.sock)"
    if grep -q '^SAXIS_DOCKER_GID=' .env 2>/dev/null; then
        sed -i "s/^SAXIS_DOCKER_GID=.*/SAXIS_DOCKER_GID=${DOCKER_GID}/" .env
    else
        echo "SAXIS_DOCKER_GID=${DOCKER_GID}" >> .env
    fi
    ok "Docker socket group detected (${DOCKER_GID})"
fi

# --------------------------------------------------------- sandbox image
if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
    info "Building the hardened sandbox image"
    docker build -t secure-ai-sandbox-runner:latest -f docker/sandbox/Dockerfile .
    ok "Sandbox image built"
fi

# ------------------------------------------------------------- database
info "Initialising the database"
(cd backend && alembic upgrade head)
ok "Database initialised"

cat <<'EOF'

Setup complete.

  Start the backend:   cd backend && ../.venv/bin/uvicorn app.main:app --host 127.0.0.1 --port 8000
  Start the frontend:  cd frontend && npm run dev
  Open:                http://127.0.0.1:5173

  Sign in with the bootstrap administrator from .env
  (SAXIS_BOOTSTRAP_ADMIN_USERNAME / SAXIS_BOOTSTRAP_ADMIN_PASSWORD).

  Run the tests:       cd backend && ../.venv/bin/pytest -q

EOF
