# ---------------------------------------------------------------------------
# One-command setup for Windows (PowerShell).
#
#   .\scripts\setup-windows.ps1
#
# The script installs the system requirements, creates a virtual
# environment, installs the pinned Python dependencies, builds the sandbox
# image and prepares the database.
# ---------------------------------------------------------------------------
#Requires -Version 5.1
[CmdletBinding()]
param(
    [switch]$SkipFrontend,
    [switch]$SkipSandboxImage
)

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $RepoRoot

function Write-Info($Message) { Write-Host "==> $Message" -ForegroundColor Blue }
function Write-Ok($Message)   { Write-Host "OK  $Message" -ForegroundColor Green }
function Write-Warn($Message) { Write-Host "!   $Message" -ForegroundColor Yellow }
function Write-Fail($Message) { Write-Host "X   $Message" -ForegroundColor Red; exit 1 }

Write-Info "Secure AI Tool Execution & Permission Sandbox - Windows setup"

# ---------------------------------------------------------------- python
$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) { Write-Fail "Python is not installed. Install Python 3.12+ from python.org." }
$version = (& python -c "import sys; print('%d.%d' % sys.version_info[:2])")
if ([version]$version -lt [version]"3.12") {
    Write-Fail "Python 3.12 or newer is required (found $version)."
}
Write-Ok "Python $version"

# ---------------------------------------------------------------- docker
$docker = Get-Command docker -ErrorAction SilentlyContinue
if (-not $docker) {
    Write-Warn "Docker is not installed."
    Write-Warn "Install Docker Desktop (Linux containers) from https://www.docker.com/products/docker-desktop/"
    Write-Warn "The sandbox backend requires Docker; the system refuses to fall back to unsandboxed execution."
} else {
    docker info *> $null
    if ($LASTEXITCODE -eq 0) {
        Write-Ok "Docker daemon is reachable"
        Write-Warn "Ensure Docker Desktop is configured to use Linux containers (Settings > General)."
    } else {
        Write-Warn "The Docker daemon is not reachable. Start Docker Desktop and try again."
    }
}

# ------------------------------------------------------------- virtualenv
if (-not (Test-Path ".venv")) {
    Write-Info "Creating the virtual environment"
    & python -m venv .venv
}
$venvPython = Join-Path $RepoRoot ".venv\Scripts\python.exe"
if (-not (Test-Path $venvPython)) { Write-Fail "The virtual environment could not be created." }
Write-Ok "Virtual environment ready"

# ----------------------------------------------------------- dependencies
Write-Info "Installing the pinned Python dependencies"
& $venvPython -m pip install --upgrade pip setuptools wheel *> $null
& $venvPython -m pip install -r backend\requirements-dev.txt
if ($LASTEXITCODE -ne 0) { Write-Fail "The Python dependencies could not be installed." }
Write-Ok "Python dependencies installed"

# ------------------------------------------------------------- frontend
if (-not $SkipFrontend) {
    $npm = Get-Command npm -ErrorAction SilentlyContinue
    if ($npm) {
        Write-Info "Installing the frontend dependencies"
        Push-Location frontend
        npm install --no-audit --no-fund
        Pop-Location
        Write-Ok "Frontend dependencies installed"
    } else {
        Write-Warn "npm is not installed; the dashboard cannot be built. Install Node.js 20+."
    }
}

# ------------------------------------------------------------ environment
if (-not (Test-Path ".env")) {
    Copy-Item ".env.example" ".env"
    $secret = & $venvPython -c "import secrets; print(secrets.token_urlsafe(48))"
    $fernet = & $venvPython -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"
    Add-Content ".env" ""
    Add-Content ".env" "# Generated by scripts/setup-windows.ps1"
    Add-Content ".env" "SAXIS_SECRET_KEY=$secret"
    Add-Content ".env" "SAXIS_PROVIDER_SECRET_KEY=$fernet"
    Write-Ok "Created .env with generated secrets (review it before deploying)"
} else {
    Write-Ok ".env already exists"
}

# --------------------------------------------------- docker socket group
if (Test-Path "\\.\pipe\docker_engine") {
    Write-Info "Docker Desktop exposes the engine through a named pipe on Windows;"
    Write-Info "the Linux containers backend provides the socket inside the VM."
    Write-Info "Set SAXIS_DOCKER_GID in .env if your distribution uses a socket file."
}

# --------------------------------------------------------- sandbox image
if (-not $SkipSandboxImage -and (Get-Command docker -ErrorAction SilentlyContinue)) {
    docker info *> $null
    if ($LASTEXITCODE -eq 0) {
        Write-Info "Building the hardened sandbox image"
        docker build -t secure-ai-sandbox-runner:latest -f docker/sandbox/Dockerfile .
        if ($LASTEXITCODE -eq 0) { Write-Ok "Sandbox image built" }
    }
}

# ------------------------------------------------------------- database
Write-Info "Initialising the database"
Push-Location backend
& $venvPython -m alembic upgrade head
Pop-Location
Write-Ok "Database initialised"

Write-Host ""
Write-Host "Setup complete." -ForegroundColor Green
Write-Host ""
Write-Host "  Start the backend:  cd backend; ..\.venv\Scripts\uvicorn.exe app.main:app --host 127.0.0.1 --port 8000"
Write-Host "  Start the frontend: cd frontend; npm run dev"
Write-Host "  Open:               http://127.0.0.1:5173"
Write-Host ""
Write-Host "  Sign in with the bootstrap administrator from .env."
Write-Host "  Run the tests:      cd backend; ..\.venv\Scripts\pytest.exe -q"
Write-Host ""
